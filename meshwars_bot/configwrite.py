"""Serialises a config dict -- the same shape `config.parse_yaml_subset()`
returns -- back out to YAML text, in the exact restricted subset
`config.py`'s hand-rolled parser understands (see that module's docstring
for the subset's rules).

Why a separate module from config.py: reading/validating and writing are
different concerns, and config.py's docstring is already dense describing
what it accepts -- it shouldn't also have to describe what gets written.

The correctness bar is round-tripping, not prettiness:

    parse_yaml_subset(write_config_text(parse_yaml_subset(x))) == parse_yaml_subset(x)

for any config text `x` the parser accepts. That means this module only
ever serialises the keys actually PRESENT in the dict it's given -- it
never invents a default for a missing key, and never silently drops a key
it doesn't recognise (unknown keys fall through to a generic scalar/list
writer). Filling in defaults is config.py's `build_config()` job, done
BEFORE a caller gets here; webui.py always validates through build_config()
first and only calls write_config() with something build_config() accepted.

The parser throws comments away, so nothing written here can be preserved
from the file it's replacing. Instead this module re-emits a standard
header plus per-field comments, reusing the wording from
config.example.yaml, so a config saved through the web UI stays exactly as
self-documenting as a hand-written one.
"""

import os
import tempfile
from typing import Any, Dict, List, Optional


class ConfigWriteError(Exception):
    """Raised when a value cannot be represented in this YAML subset."""


# ---------------------------------------------------------------------------
# Low-level scalar/list rendering
# ---------------------------------------------------------------------------


def _yaml_scalar(value: Any) -> str:
    """Render one scalar in a form `config.py`'s parser reads back exactly.

    Booleans and ints are written bare; everything else is double-quoted.
    `None` is written as nothing at all -- `key:` with a blank value is
    exactly what `_parse_scalar("")` reads back as None.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if value is None:
        return ""
    text = str(value)
    # The parser strips one matching pair of quotes and does no escaping
    # (see config.py's _parse_scalar) -- a literal quote or backslash
    # cannot round-trip through this subset. Refuse rather than emit a
    # file the parser would misread.
    if '"' in text or "\\" in text:
        raise ConfigWriteError(
            f"value {text!r} contains a double-quote or backslash, which this "
            "YAML subset cannot write and read back safely"
        )
    return f'"{text}"'


def _yaml_flow_list(items: List[Any]) -> str:
    return "[" + ", ".join(_yaml_scalar(v) for v in items) + "]"


def _render_value(value: Any) -> str:
    if isinstance(value, list):
        return _yaml_flow_list(value)
    if isinstance(value, dict):
        raise ConfigWriteError("flow mappings are not supported by this YAML subset")
    return _yaml_scalar(value)


def _comment_block(lines: List[str], indent: int) -> List[str]:
    pad = " " * indent
    return [f"{pad}# {line}" if line else f"{pad}#" for line in lines]


def _field_line(key: str, value: Any, indent: int, trailing_comment: Optional[str] = None) -> str:
    pad = " " * indent
    line = f"{pad}{key}: {_render_value(value)}"
    if trailing_comment:
        line += f"   # {trailing_comment}"
    return line


