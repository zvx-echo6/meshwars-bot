def _write_known_fields(
    out: List[str], mapping: Dict[str, Any], order: List[str], indent: int, comments: Dict[str, List[str]]
) -> List[str]:
    """Emit fields in `order` that are present in `mapping`, each preceded
    by its comment block, then any remaining keys not in `order` as plain
    (uncommented) lines so nothing present in the input is ever dropped."""
    remaining = dict(mapping)
    for key in order:
        if key not in mapping:
            continue
        comment = comments.get(key)
        if comment:
            out.extend(_comment_block(comment, indent))
        out.append(_field_line(key, mapping[key], indent))
        del remaining[key]
    for key, value in remaining.items():
        out.append(_field_line(key, value, indent))
    return out


def _write_destination(out: List[str], dest: Dict[str, Any]) -> None:
    name = dest.get("name", "")
    out.append(f"  # --- {name} ---" if name else "  # ---")
    remaining = dict(dest)
    first = True
    for key, short_comment in _DESTINATION_FIELD_ORDER:
        if key not in dest:
            continue
        prefix = "  - " if first else "    "
        first = False
        out.append(f"{prefix}{key}: {_render_value(dest[key])}" + (f"   # {short_comment}" if short_comment else ""))
        del remaining[key]
    for key, value in remaining.items():
        prefix = "  - " if first else "    "
        first = False
        out.append(f"{prefix}{key}: {_render_value(value)}")


def write_config_text(raw: Dict[str, Any]) -> str:
    """Render `raw` (a dict shaped like config.parse_yaml_subset()'s output)
    as YAML text in config.py's supported subset. Only keys present in
    `raw` (and, within `feed`/`web`/each destination, only keys present in
    THOSE sub-dicts) are written."""
    out: List[str] = []
    out.extend(_comment_block(_HEADER, 0))
    out.append("")

    if "feed" in raw:
        if not raw["feed"]:
            # parse_yaml_subset() can never actually produce an empty-but-
            # present dict here -- `feed:` with nothing under it parses as
            # None, not {} (see config.py's _parse_mapping) -- and flow
            # mappings (`feed: {}`) aren't supported by that parser at all.
            # So this can only happen from a hand-built raw dict, and there
            # is no way to write it that round-trips; fail loudly instead
            # of silently writing something parse_yaml_subset reads back
            # differently.
            raise ConfigWriteError("'feed' is present but empty -- cannot round-trip an empty mapping in this YAML subset")
        out.append("feed:")
        _write_known_fields(
            out,
            raw["feed"],
            ["base_url", "api_key", "timeout_seconds"],
            2,
            {
                "base_url": _FEED_BASE_URL_COMMENT,
                "api_key": _FEED_API_KEY_COMMENT,
                "timeout_seconds": _FEED_TIMEOUT_COMMENT,
            },
        )
        out.append("")

    if "state_path" in raw:
        out.extend(_comment_block(_STATE_PATH_COMMENT, 0))
        out.append(_field_line("state_path", raw["state_path"], 0))
        out.append("")

    if "web" in raw:
        if not raw["web"]:
            raise ConfigWriteError("'web' is present but empty -- cannot round-trip an empty mapping in this YAML subset")
        out.extend(_comment_block(_WEB_COMMENT, 0))
        out.append("web:")
        _write_known_fields(
            out, raw["web"], ["enabled", "bind_host", "bind_port"], 2, {}
        )
        out.append("")

    if "destinations" in raw:
        out.extend(_comment_block(_DESTINATIONS_HEADER_COMMENT, 0))
        destinations = raw["destinations"]
        if not destinations:
            # An empty block sequence (`destinations:` with nothing under
            # it) parses back as None, not `[]` -- the inline flow form is
            # the only way to round-trip an explicitly empty list.
            out.append("destinations: []")
        else:
            out.append("destinations:")
            for dest in destinations:
                _write_destination(out, dest)
        out.append("")

    # Anything at the top level this module doesn't specifically know about
    # (there shouldn't be any, given build_config()'s validation runs
    # first, but never silently drop it).
    known_top = {"feed", "state_path", "web", "destinations"}
    for key, value in raw.items():
        if key in known_top:
            continue
        out.append(_field_line(key, value, 0))

    text = "\n".join(out).rstrip("\n") + "\n"
    return text


def write_config(raw: Dict[str, Any], path: str) -> None:
    """Atomically write `raw` as YAML to `path` (temp file + os.replace, same
    pattern as state.py's save_state -- a crash mid-write must never leave a
    half-written config file)."""
    text = write_config_text(raw)
    directory = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(directory, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix=".meshwars-bot-config-", suffix=".tmp", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_path, path)
    except BaseException:
        try:
            os.remove(tmp_path)
        except OSError:
            pass
        raise
